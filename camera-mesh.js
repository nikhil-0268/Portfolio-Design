  function triangulate(vertices) {
    const pts = vertices.map((p) => p.slice());
    const n = pts.length;
    pts.push([-10000, -10000], [10000, -10000], [0, 10000]);
    let triangles = [[n, n + 1, n + 2]];
    function circle(t, p) {
      const [a, b, c] = t.map((i) => pts[i]);
      const d = 2 * (a[0] * (b[1] - c[1]) + b[0] * (c[1] - a[1]) + c[0] * (a[1] - b[1]));
      if (Math.abs(d) < 1e-8) return false;
      const aa = a[0] * a[0] + a[1] * a[1],
        bb = b[0] * b[0] + b[1] * b[1],
        cc = c[0] * c[0] + c[1] * c[1];
      const x = (aa * (b[1] - c[1]) + bb * (c[1] - a[1]) + cc * (a[1] - b[1])) / d;
      const y = (aa * (c[0] - b[0]) + bb * (a[0] - c[0]) + cc * (b[0] - a[0])) / d;
      return (p[0] - x) ** 2 + (p[1] - y) ** 2 <= (a[0] - x) ** 2 + (a[1] - y) ** 2 + 0.001;
    }
    for (let i = 0; i < n; i++) {
      const bad = triangles.filter((t) => circle(t, pts[i]));
      const edges = new Map();
      for (const t of bad)
        for (let k = 0; k < 3; k++) {
          const e = [t[k], t[(k + 1) % 3]],
            key = e
              .slice()
              .sort((a, b) => a - b)
              .join(',');
          if (edges.has(key)) edges.delete(key);
          else edges.set(key, e);
        }
      triangles = triangles.filter((t) => !bad.includes(t));
      for (const e of edges.values()) triangles.push([e[0], e[1], i]);
    }
    return triangles.filter((t) => t.every((i) => i < n));
  }
